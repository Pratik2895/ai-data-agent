class SQLAgentState(BaseModel):
    """State carried through every node of the SQL Analyst stateful graph.

    Each node reads from and writes to this state, maintaining context
    across the entire pipeline without losing intermediate results.
    """
    messages: list = Field(default_factory=list,
        description="Chat messages processed by the SQL agent")
    user_question: str = Field(default="", description="Raw user input")
    curated_question: str = Field(default="", description="Refined user question")
    prompt_context: str = Field(default="", description="Prompt with DB schema context")
    generated_sql: str = Field(default="", description="SQL generated by LLM")
    is_safe: Literal["yes", "no"] = Field(default="no", description="Safety flag from AI judge")
    judge_comments: str = Field(default="", description="Judge feedback")
    sql_result: str = Field(default="", description="SQL execution result")
    final_answer: str = Field(default="", description="User-facing answer")


class JudgeSchema(BaseModel):
    """Structured output schema for the AI-as-judge SQL safety check."""
    answer: Literal["yes", "no"] = Field(description="Whether the SQL query is safe to execute")
    comments: str = Field(default="", description="Feedback from the judge")


class RouterSchema(BaseModel):
    """Structured output schema for the AI-decide router."""
    answer: Literal["SQL", "ETL", "KNOWLEDGE"] = Field(
        description="Route: SQL for data queries, ETL for extract/transform/load, KNOWLEDGE for product docs")
    comments: str = Field(default="", description="Brief justification for routing")


class ETLAgentState(BaseModel):
    """State for the ETL Analyst ReAct loop."""
    messages: Annotated[list, add] = Field(default_factory=list,
        description="Chat messages for the ETL agent")


class KnowledgeAgentState(BaseModel):
    """State for the Knowledge Search agent."""
    messages: Annotated[list, add] = Field(default_factory=list,
        description="Chat messages for the knowledge agent")
    search_results: str = Field(default="", description="Product documentation search results")
    final_answer: str = Field(default="", description="User-facing answer")


class DataAgentState(BaseModel):
    """State for the parent Data Agent orchestrator."""
    messages: Annotated[list, add] = Field(default_factory=list,
        description="Chat messages for the parent agent")
    route: str = Field(default="", description="Routing decision: SQL, ETL, or KNOWLEDGE")
    final_answer: str = Field(default="", description="Final user-facing answer")


# ════════════════════════════════════════════════════════════════
# LLM PICKER — Route to the right model for the right task
# Low-end for curation/formatting, Medium for SQL/code,
# High-end for complex reasoning and routing decisions.
# ════════════════════════════════════════════════════════════════

def message_text(message):
    content = message.content
    if isinstance(content, str):
        return content
    return "\n".join(block.get("text", "") for block in content
                     if isinstance(block, dict) and block.get("type") in ("text", "output_text"))


def pick_llm(level: str = "low"):
    """Return a ChatDatabricks instance based on task complexity.

    This demonstrates LLM ROUTING — using cheaper models for simple tasks
    (question curation, response formatting) and more capable models for
    complex tasks (SQL generation, routing decisions) to optimize cost.
    """
    from databricks_langchain import ChatDatabricks
    level = level.lower().strip()
    if level == "low":
        return ChatDatabricks(endpoint=LLM_LOW, temperature=0)
    elif level == "medium":
        return ChatDatabricks(endpoint=LLM_MEDIUM, temperature=0)
    elif level == "high":
        return ChatDatabricks(endpoint=LLM_HIGH, temperature=0)
    else:
        return ChatDatabricks(endpoint=LLM_LOW, temperature=0)


