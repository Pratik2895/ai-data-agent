"""
AI Data Agent — Multi-Agent System for Databricks Model Serving.

ARCHITECTURE (mirrors the tutorial transcript):
  ┌───────────────────────────────────────────────────────┐
  │                   DATA AGENT (Parent)                  │
  │                  ┌──── AI-DECIDE ────┐                 │
  │                  │    Router Node    │                 │
  │                  └──┬────┬────┬────┘                 │
  │             SQL      │    │    │  KNOWLEDGE            │
  │              ┌───────┘    │    └────────┐              │
  │     SQL ANALYST    ETL ANALYST   KNOWLEDGE SEARCH      │
  │    (Stateful)      (ReAct Loop)   (Vector Search)     │
  │  Curate→Context   Reason→Act→     Search PDF docs    │
  │  →Generate→Judge   Reason→Act       Return results    │
  │  →Execute→Format                                        │
  └───────────────────────────────────────────────────────┘

Key Concepts Demonstrated:
  • Stateful Orchestration (Pydantic models, LangGraph state)
  • ReAct Architecture (Reason + Act loops)
  • Context Engineering (schema introspection, dynamic context)
  • AI-as-Judge (structured output for SQL safety check)
  • LLM Routing (low/medium/high models per task complexity)
  • Sub-Agent coordination (parent routes to specialized agents)
  • UC Functions as agent tools (Unity Catalog function toolkit)
  • Model Serving deployment (ResponsesAgent pattern)
"""
