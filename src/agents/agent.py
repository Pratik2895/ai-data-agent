# RESPONSES AGENT — MLflow Model Serving wrapper
# This is the interface that Model Serving calls when the endpoint
# receives a request from the Databricks App or external clients.
# ════════════════════════════════════════════════════════════════

class DataAgent(ResponsesAgent):
    """Multi-Agent Data Agent deployed via MLflow Model Serving.

    Wraps the LangGraph multi-agent system in the ResponsesAgent interface
    so it can be deployed as a Model Serving endpoint and called from
    the Databricks App (browser UI).
    """

    def __init__(self):
        self.graph = None

    def predict(self, request: ResponsesAgentRequest) -> ResponsesAgentResponse:
        """Non-streaming prediction — routes user query through the full agent graph."""
        outputs = [
            event.item
            for event in self.predict_stream(request)
            if event.type == "response.output_item.done"
        ]
        return ResponsesAgentResponse(output=outputs)

    def predict_stream(
        self, request: ResponsesAgentRequest
    ) -> Generator[ResponsesAgentStreamEvent, None, None]:
        """Streaming prediction — streams agent responses as they are generated."""
        try:
            raw_messages = to_chat_completions_input([m.model_dump() for m in request.input])

            # Convert dict messages to LangChain message objects
            lc_messages = []
            for m in raw_messages:
                if isinstance(m, dict):
                    role = m.get("role", "user")
                    content = m.get("content", "")
                    if role == "assistant":
                        lc_messages.append(AIMessage(content=content))
                    else:
                        lc_messages.append(HumanMessage(content=content))
                else:
                    lc_messages.append(m)

            # Run the full multi-agent graph
            if self.graph is None:
                self.graph = _build_data_agent_graph()
            result = self.graph.invoke({"messages": lc_messages})

            # Extract the final answer
            final_answer = result.get("final_answer", "")
            if not final_answer and result.get("messages"):
                last_msg = result["messages"][-1]
                final_answer = message_text(last_msg) if hasattr(last_msg, 'content') else str(last_msg)
        except Exception as e:
            logger.exception("Agent execution failed")
            raise

        # Yield as a text output item
        yield ResponsesAgentStreamEvent(
            type="response.output_item.done",
            item=self.create_text_output_item(text=final_answer, id="msg_final"),
        )


