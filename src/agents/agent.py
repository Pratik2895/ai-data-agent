# SQL ANALYST SUB-AGENT — Stateful LangGraph
# Nodes: curate → context → generate → judge → [execute | cancel] → format
# Demonstrates: stateful orchestration, context engineering, AI-as-judge
# ════════════════════════════════════════════════════════════════

def _curate_question(state: SQLAgentState) -> SQLAgentState:
    """Node 1: Curate the user's raw question into a clear, structured query."""
    llm = pick_llm("low")  # Low-end LLM — simple text curation
    prompt = f"Curate the following question so that it is clear, specific, and well-structured. Output only the curated question, nothing else:\n\n{state.user_question}"
    response = llm.invoke(prompt)
    state.curated_question = message_text(response)
    state.messages = state.messages + [HumanMessage(content=message_text(response))]
    return state


def _add_context(state: SQLAgentState) -> SQLAgentState:
    """Node 2: Add database schema context to the curated question.

    CONTEXT ENGINEERING: Call the get_schema_info UC function to get table
    names, column types so the LLM can generate syntactically correct SQL.
    """
    schema_info = _execute_sql_sdk(f"SELECT {CATALOG}.{SCHEMA}.get_schema_info()")
    if "Error" in schema_info:
        schema_info = f"Tables: {CATALOG}.{SCHEMA}.cust_service_data, {CATALOG}.{SCHEMA}.policies"

    prompt = f"""You are a SQL analyst agent. Convert the user's question into a valid Databricks SQL query.

User question: {state.curated_question}

Database schema details (Delta tables in Unity Catalog):
{schema_info}

Rules:
- Generate ONLY the SQL query without any explanation.
- Always LIMIT output to 10 rows unless user asks for more.
- Use the exact table and column names from the schema above.
- Tables are in {CATALOG}.{SCHEMA} catalog.schema — use fully qualified names.

SQL query:"""
    state.prompt_context = prompt
    return state


def _generate_sql(state: SQLAgentState) -> SQLAgentState:
    """Node 3: Generate SQL using a medium-end LLM with full context."""
    llm = pick_llm("medium")  # Medium LLM — code/SQL generation needs accuracy
    response = llm.invoke(state.prompt_context)
    state.generated_sql = message_text(response).strip()
    if state.generated_sql.startswith("```sql"):
        state.generated_sql = state.generated_sql[6:]
    if state.generated_sql.startswith("```"):
        state.generated_sql = state.generated_sql[3:]
    if state.generated_sql.endswith("```"):
        state.generated_sql = state.generated_sql[:-3]
    state.generated_sql = state.generated_sql.strip()
    return state


def _is_safe_sql(state: SQLAgentState) -> SQLAgentState:
    """Node 4: AI-as-Judge — check if the generated SQL is safe to execute.

    Uses structured output (Pydantic schema) to force the LLM to return
    a yes/no verdict with justification. This is a guardrail against
    SQL injection and destructive queries.
    """
    try:
        from .runtime import validate_sql
    except ImportError:
        from runtime import validate_sql
    try:
        validate_sql(state.generated_sql)
    except ValueError as exc:
        state.is_safe = "no"
        state.judge_comments = str(exc)
        return state
    llm = pick_llm("low")
    llm_judge = llm.with_structured_output(JudgeSchema)
    judge_prompt = f"""You are a SQL judge for data security. Determine whether the SQL query is safe to execute.

The SQL query should ONLY be used for data retrieval (SELECT) and should NOT modify the database.
Reject any INSERT, UPDATE, DELETE, DROP, TRUNCATE, ALTER, or other DDL/DML commands.

SQL query to validate:
{state.generated_sql}"""
    response = llm_judge.invoke(judge_prompt)
    result = response.model_dump() if hasattr(response, 'model_dump') else {"answer": "no", "comments": str(response)}
    state.is_safe = result.get("answer", "no")
    state.judge_comments = result.get("comments", "")
    return state


def _execute_sql(state: SQLAgentState) -> SQLAgentState:
    """Node 5a: Execute the safe SQL query via Databricks SDK (works in Model Serving)."""
    state.sql_result = _execute_sql_sdk(state.generated_sql)
    return state


def _cancel_sql(state: SQLAgentState) -> SQLAgentState:
    """Node 5b: Cancel execution — query was deemed unsafe."""
    state.final_answer = f"⚠️ The generated SQL query was deemed unsafe to execute.\n\nReason: {state.judge_comments}\n\nGenerated query: {state.generated_sql}"
    state.messages = state.messages + [AIMessage(content=state.final_answer)]
    return state


def _format_answer(state: SQLAgentState) -> SQLAgentState:
    """Node 6: Format the execution results into a user-friendly response."""
    llm = pick_llm("low")  # Low-end LLM — simple summarization
    prompt = f"""You are a SQL analyst. Provide the final answer based on the execution result.
The answer should be concise, clear, and address the user's question.
Do NOT include SQL code in the answer.

User's original question: {state.curated_question}

Execution result:
{state.sql_result}"""
    response = llm.invoke(prompt)
    state.final_answer = message_text(response)
    state.messages = state.messages + [AIMessage(content=state.final_answer)]
    return state


def _safety_edge(state: SQLAgentState) -> str:
    """Conditional edge: route based on the AI judge's safety verdict."""
    if state.is_safe.lower() == "yes":
        return "execute_sql"
    return "cancel_sql"


def _build_sql_analyst_graph():
    """Build and compile the SQL Analyst stateful graph.

    Graph flow:
      START → curate_question → add_context → generate_sql → is_safe_sql
        → [yes] → execute_sql → format_answer → END
        → [no]  → cancel_sql → END
    """
    graph = StateGraph(SQLAgentState)
    graph.add_node("curate_question", RunnableLambda(_curate_question))
    graph.add_node("add_context", RunnableLambda(_add_context))
    graph.add_node("generate_sql", RunnableLambda(_generate_sql))
    graph.add_node("is_safe_sql", RunnableLambda(_is_safe_sql))
    graph.add_node("execute_sql", RunnableLambda(_execute_sql))
    graph.add_node("cancel_sql", RunnableLambda(_cancel_sql))
    graph.add_node("format_answer", RunnableLambda(_format_answer))

    graph.add_edge(START, "curate_question")
    graph.add_edge("curate_question", "add_context")
    graph.add_edge("add_context", "generate_sql")
    graph.add_edge("generate_sql", "is_safe_sql")
    graph.add_conditional_edges("is_safe_sql", _safety_edge,
        {"execute_sql": "execute_sql", "cancel_sql": "cancel_sql"})
    graph.add_edge("execute_sql", "format_answer")
    graph.add_edge("cancel_sql", END)
    graph.add_edge("format_answer", END)
    return graph.compile()


# ════════════════════════════════════════════════════════════════
# ETL ANALYST SUB-AGENT — ReAct Loop (Reasoning + Acting)
# Uses UC Function tools in a tool-calling loop.
# Demonstrates: ReAct architecture, tool calling, react loops
# ════════════════════════════════════════════════════════════════

def _build_etl_analyst_graph():
    """Build and compile the ETL Analyst ReAct agent.

    Graph flow (ReAct loop):
      START → llm_node ↔ tool_node
        → [has tool calls] → tool_node → llm_node (loop)
        → [no tool calls]  → END
    """
    try:
        from .runtime import etl_tools
    except ImportError:
        from runtime import etl_tools
    tools = etl_tools()
    llm = pick_llm("high")  # High-end LLM for agentic tool-calling loops

    if tools:
        llm_with_tools = llm.bind_tools(tools)
    else:
        llm_with_tools = llm

    system_prompt = (
        "You are a Python data analyst ETL agent. You have access to tools for "
        "extracting allowlisted HTTPS JSON APIs, inspecting datasets, and applying declarative transformations. "
        "When the user asks to extract, transform, load, or analyze data, "
        "use the appropriate tools. If the task is complete, provide a direct answer."
    )

    def _etl_llm_node(state: ETLAgentState) -> dict:
        messages = [SystemMessage(content=system_prompt)] + state.messages
        response = llm_with_tools.invoke(messages)
        return {"messages": [response]}

    def _should_continue(state: ETLAgentState) -> str:
        last = state.messages[-1] if state.messages else None
        if isinstance(last, AIMessage) and getattr(last, "tool_calls", None):
            return "tool_node"
        return END

    graph = StateGraph(ETLAgentState)
    graph.add_node("llm_node", RunnableLambda(_etl_llm_node))

    if tools:
        graph.add_node("tool_node", ToolNode(tools))
        graph.add_edge(START, "llm_node")
        graph.add_conditional_edges("llm_node", _should_continue,
            {"tool_node": "tool_node", END: END})
        graph.add_edge("tool_node", "llm_node")
    else:
        graph.add_edge(START, "llm_node")
        graph.add_edge("llm_node", END)

    return graph.compile()


# ════════════════════════════════════════════════════════════════
# KNOWLEDGE SEARCH SUB-AGENT — Search parsed PDF product docs
# Uses UC function search_product_docs to find relevant docs.
# ════════════════════════════════════════════════════════════════

def _build_knowledge_search_graph():
    """Build the Knowledge Search agent that queries parsed PDF documentation."""
    tools = _get_uc_tools()
    llm = pick_llm("medium")

    system_prompt = (
        "You are a knowledge search agent for customer support. You have access to "
        "product documentation stored in Databricks. Use the search_product_docs tool "
        "to find relevant product information and answer the user's question. "
        "If no relevant documentation is found, say so clearly. Cite the document filenames returned by the tool."
    )

    knowledge_tools = [t for t in tools if "search_product_docs" in getattr(t, "name", "")]
    if knowledge_tools:
        llm_with_tools = llm.bind_tools(knowledge_tools)
    else:
        llm_with_tools = llm

    def _knowledge_llm_node(state: KnowledgeAgentState) -> dict:
        messages = [SystemMessage(content=system_prompt)] + state.messages
        response = llm_with_tools.invoke(messages)
        return {"messages": [response]}

    def _should_continue_knowledge(state: KnowledgeAgentState) -> str:
        last = state.messages[-1] if state.messages else None
        if isinstance(last, AIMessage) and getattr(last, "tool_calls", None):
            return "tool_node"
        return END

    graph = StateGraph(KnowledgeAgentState)
    graph.add_node("llm_node", RunnableLambda(_knowledge_llm_node))

    if knowledge_tools:
        graph.add_node("tool_node", ToolNode(knowledge_tools))
        graph.add_edge(START, "llm_node")
        graph.add_conditional_edges("llm_node", _should_continue_knowledge,
            {"tool_node": "tool_node", END: END})
        graph.add_edge("tool_node", "llm_node")
    else:
        graph.add_edge(START, "llm_node")
        graph.add_edge("llm_node", END)

    return graph.compile()


# ════════════════════════════════════════════════════════════════
# AI-DECIDE ROUTER — Parent Data Agent with intelligent routing
# Demonstrates: sub-agent coordination, LLM routing with structured output
# ════════════════════════════════════════════════════════════════

def _build_data_agent_graph():
    """Build the parent Data Agent that routes to sub-agents.

    Graph flow:
      START → router_node
        → [SQL]      → sql_node      → END
        → [ETL]      → etl_node      → END
        → [KNOWLEDGE] → knowledge_node → END
    """
    llm = pick_llm("high")  # High-end LLM for accurate routing decisions
    llm_router = llm.with_structured_output(RouterSchema)

    sql_analyst = _build_sql_analyst_graph()
    etl_analyst = _build_etl_analyst_graph()
    knowledge_agent = _build_knowledge_search_graph()

    def _router_node(state: DataAgentState) -> dict:
        """AI-DECIDE: Classify the user query and route to the right sub-agent."""
        message = state.messages[-1].content if state.messages else ""
        router_prompt = f"""You are a router for a multi-agent data system. Classify the user's question:

- Answer 'SQL' for data retrieval, analytics, aggregations, or queries about customer service data, policies, or products.
- Answer 'ETL' for extracting, transforming, loading, or fetching data from external sources.
- Answer 'KNOWLEDGE' for questions about product documentation, specs, features, or manuals.

User question: {message}"""
        response = llm_router.invoke(router_prompt)
        result = response.model_dump() if hasattr(response, 'model_dump') else {"answer": "SQL"}
        return {"route": result.get("answer", "SQL")}

    def _sql_node(state: DataAgentState) -> dict:
        """Invoke the SQL Analyst sub-agent."""
        message = "\n".join(f"{m.type}: {m.content}" for m in state.messages)
        sql_input = SQLAgentState(messages=[], user_question=message)
        result = sql_analyst.invoke(sql_input)
        final = result["final_answer"]
        return {"final_answer": final, "messages": [AIMessage(content=final)]}

    def _etl_node(state: DataAgentState) -> dict:
        """Invoke the ETL Analyst sub-agent (ReAct loop)."""
        message = state.messages[-1].content if state.messages else ""
        etl_input = ETLAgentState(messages=[HumanMessage(content=message)])
        result = etl_analyst.invoke({"messages": state.messages}, config={"recursion_limit": 20})
        if result.get("messages"):
            final = message_text(result["messages"][-1])
        else:
            final = str(result)
        return {"final_answer": final, "messages": [AIMessage(content=final)]}

    def _knowledge_node(state: DataAgentState) -> dict:
        """Invoke the Knowledge Search sub-agent."""
        message = state.messages[-1].content if state.messages else ""
        knowledge_input = KnowledgeAgentState(messages=[HumanMessage(content=message)])
        result = knowledge_agent.invoke({"messages": state.messages}, config={"recursion_limit": 20})
        if result.get("messages"):
            final = message_text(result["messages"][-1])
        else:
            final = str(result)
        return {"final_answer": final, "messages": [AIMessage(content=final)]}

    def _router_edge(state: DataAgentState) -> str:
        route = state.route.upper()
        if route == "ETL":
            return "etl_node"
        elif route == "KNOWLEDGE":
            return "knowledge_node"
        return "sql_node"

    graph = StateGraph(DataAgentState)
    graph.add_node("router_node", RunnableLambda(_router_node))
    graph.add_node("sql_node", RunnableLambda(_sql_node))
    graph.add_node("etl_node", RunnableLambda(_etl_node))
    graph.add_node("knowledge_node", RunnableLambda(_knowledge_node))

    graph.add_edge(START, "router_node")
    graph.add_conditional_edges("router_node", _router_edge,
        {"sql_node": "sql_node", "etl_node": "etl_node", "knowledge_node": "knowledge_node"})
    graph.add_edge("sql_node", END)
    graph.add_edge("etl_node", END)
    graph.add_edge("knowledge_node", END)

    return graph.compile()


